import 'dart:io';

void main() {
  const sourcePath = '../brothers_tech_website/index.html';
  final source = File(sourcePath);
  if (!source.existsSync()) {
    stderr.writeln('Could not find $sourcePath.');
    exitCode = 1;
    return;
  }

  final html = source.readAsStringSync();
  final match = RegExp(
    r'<script\s+id="tailwind-config">([\s\S]*?)</script>',
    caseSensitive: false,
  ).firstMatch(html);
  if (match == null) {
    stderr.writeln('Could not find the Tailwind theme in $sourcePath.');
    exitCode = 1;
    return;
  }

  final temporaryConfig = File('${Directory.systemTemp.path}/bro_tech_tailwind_config.js');
  temporaryConfig.writeAsStringSync('${match.group(1)!.trim()}\n');
  final result = Process.runSync('node', [
    '-e',
    'global.tailwind={};require(${_jsString(temporaryConfig.path)});process.stdout.write(JSON.stringify(tailwind.config));',
  ]);
  if (result.exitCode != 0) {
    stderr.write(result.stderr);
    exitCode = result.exitCode;
    return;
  }

  Directory('lib/styles').createSync(recursive: true);
  File('lib/styles/tailwind_theme.g.dart').writeAsStringSync('''
// Generated by tool/import_tailwind_theme.dart.
// The value is JSON theme data consumed by the Tailwind browser runtime.
const tailwindThemeJson = r\'''${result.stdout}\''';
''');
  stdout.writeln('Converted the Tailwind JavaScript configuration into Dart theme data.');
}

String _jsString(String value) {
  return "'${value.replaceAll(r'\\', r'\\\\').replaceAll("'", r"\\'")}'";
}
